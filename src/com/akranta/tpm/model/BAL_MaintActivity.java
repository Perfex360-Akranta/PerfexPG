package com.akranta.tpm.model;

public class BAL_MaintActivity {
	
	
	private String assembly;
	private String whenFreq;
	private String date;
	private String type;
	private String duration;
	private String status;
	private String groupByMachine;
	private String groupByDuration;
	private String count;
	
	public String getAssembly() {
		return assembly;
	}
	public void setAssembly(String assembly) {
		this.assembly = assembly;
	}
	public String getWhenFreq() {
		return whenFreq;
	}
	public void setWhenFreq(String whenFreq) {
		this.whenFreq = whenFreq;
	}
	public String getDate() {
		return date;
	}
	public void setDate(String date) {
		this.date = date;
	}
	public String getType() {
		return type;
	}
	public void setType(String type) {
		this.type = type;
	}
	public String getDuration() {
		return duration;
	}
	public void setDuration(String duration) {
		this.duration = duration;
	}
	public String getStatus() {
		return status;
	}
	public void setStatus(String status) {
		this.status = status;
	}
	public String getGroupByMachine() {
		return groupByMachine;
	}
	public void setGroupByMachine(String groupByMachine) {
		this.groupByMachine = groupByMachine;
	}
	public String getGroupByDuration() {
		return groupByDuration;
	}
	public void setGroupByDuration(String groupByDuration) {
		this.groupByDuration = groupByDuration;
	}
	public String getCount() {
		return count;
	}
	public void setCount(String count) {
		this.count = count;
	}

}
