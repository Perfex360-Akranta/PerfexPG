public class ChartToolTip {
	private String x;
	private String y;
	private Boolean shared;
	
	public String getX() {
		return x;
	}
	public void setX(String x) {
		this.x = x;
	}
	public String getY() {
		return y;
	}
	public void setY(String y) {
		this.y = y;
	}
	public void setShared(Boolean shared) {
		this.shared = shared;
	}
	public Boolean getShared() {
		return shared;
	}
	

}
