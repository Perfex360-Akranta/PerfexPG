package com.akranta.tpm.bean;

public class ChangePwdBean {
	
	private String cpwdUsername;
	private String cpwdOldpwd;
	private String cpwdNewpwd;
	private String cpwdConfpwd;
	
	public String getCpwdUsername() {
		return cpwdUsername;
	}
	public void setCpwdUsername(String cpwdUsername) {
		this.cpwdUsername = cpwdUsername;
	}
	public String getCpwdOldpwd() {
		return cpwdOldpwd;
	}
	public void setCpwdOldpwd(String cpwdOldpwd) {
		this.cpwdOldpwd = cpwdOldpwd;
	}
	public String getCpwdNewpwd() {
		return cpwdNewpwd;
	}
	public void setCpwdNewpwd(String cpwdNewpwd) {
		this.cpwdNewpwd = cpwdNewpwd;
	}
	public String getCpwdConfpwd() {
		return cpwdConfpwd;
	}
	public void setCpwdConfpwd(String cpwdConfpwd) {
		this.cpwdConfpwd = cpwdConfpwd;
	}
	

}
